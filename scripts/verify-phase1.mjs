import assert from 'node:assert/strict';
import fs from 'node:fs';
import Database from 'better-sqlite3';
const base=process.env.APP_URL || 'http://127.0.0.1:3000';
const id=process.argv[2];
assert.ok(id,'Pass the verified story ID');
const {chat}=await (await fetch(`${base}/api/chats/${id}`)).json();
assert.equal(chat.settings.customModel,process.env.EXPECTED_MODEL || 'qwen3.5:4b');
assert.equal(chat.settings.imageBackend,'manual');
const illustrated=chat.messages.find(m=>m.imageRequest?.needed);
assert.ok(illustrated?.imageRequest.prompt?.length>100,'Real model image request persisted');
assert.ok(illustrated.content.length>50,'Narration accompanies the tool call');
assert.equal(illustrated.imageRequest.backend,'manual');
assert.equal(illustrated.imageRequest.aspect,'landscape');
assert.ok(illustrated.imageRequest.characterIds.includes(chat.characters[0].id));
assert.ok(!illustrated.generatedImage,'No local rendering');
assert.ok(!chat.messages.some(m=>m.role==='assistant'&&/generate_image|<tool_call>|<think>/.test(m.content)),'Tool/reasoning syntax stays out of prose');
assert.ok(chat.messages.at(-1).role==='assistant' && chat.messages.at(-1).id!==illustrated.id,'Story continued after image request');
assert.equal(chat.characters[0].skills,'Navigation, ancient scripts');
const guard=await fetch(base+'/api/images',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({backend:'manual',prompt:'Do not render: guard test'})});
assert.equal(guard.status,409,'Manual backend refuses local generation');
const db=new Database('data/local-roleplay.sqlite',{readonly:true});
assert.equal(db.pragma('integrity_check',{simple:true}),'ok');
const row=db.prepare('SELECT image_request_json,generated_image_json FROM messages WHERE id=?').get(illustrated.id);
assert.equal(JSON.parse(row.image_request_json).prompt,illustrated.imageRequest.prompt);
assert.equal(row.generated_image_json,null);
const memory=db.prepare('SELECT story_summary,story_summary_count FROM chats WHERE id=?').get(id);
const result={verifiedAt:new Date().toISOString(),chatId:id,messageCount:chat.messages.length,characterCount:chat.characters.length,imageRequest:illustrated.imageRequest,sqliteIntegrity:'ok',summary:memory};
fs.mkdirSync('logs',{recursive:true});fs.writeFileSync('logs/phase1-persistence.json',JSON.stringify(result,null,2));
db.close();console.log(JSON.stringify(result,null,2));
